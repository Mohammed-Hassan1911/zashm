// ─── ZASHM RESILIENCE HELPERS ────────────────────────────────────────────────
// Small, dependency-free helpers used by the storefront when Supabase (or its
// Storage) is unavailable:
//
//   * mirrorUrl()         map a Supabase Storage public URL to its local copy
//   * mirrorCandidates()  try the original URL first, then the local copy
//   * fetchCatalogSnapshot() read the same-origin catalogue snapshot
//   * whatsappUrl()/cartWhatsAppMessage() hand an order to the support line
//
// The image mirror lives under /media on the same origin (written by
// scripts/resilience-sync.mjs and served by Vercel's CDN). It needs no account,
// no credential, and no CSP change: if Supabase Storage is down, the browser
// simply loads the copy that shipped with the site.

/** Same-origin folder that mirrors the Supabase `products` bucket. */
export const MEDIA_MIRROR_PREFIX = '/media';

/** Same-origin catalogue snapshot generated by scripts/resilience-sync.mjs. */
export const SNAPSHOT_PATH = '/catalog-snapshot.json';

/** ZASHM support line (01013380313). Keep in sync with WhatsAppButton.js. */
export const WHATSAPP_NUMBER = '201013380313';

const SUPABASE_PUBLIC_MARKER = '/storage/v1/object/public/';

/**
 * Map a Supabase Storage public URL to its committed same-origin copy.
 *
 *   https://<ref>.supabase.co/storage/v1/object/public/products/a.jpg
 *     -> /media/products/a.jpg
 *
 * Returns '' for non-Supabase URLs (external images stay untouched), for URLs
 * that are already local, and for anything that would escape the folder.
 */
export function mirrorUrl(originalUrl, prefix = MEDIA_MIRROR_PREFIX) {
  if (typeof originalUrl !== 'string' || !originalUrl) return '';
  const base = String(prefix || '').replace(/\/+$/, '');
  if (!base) return '';
  if (originalUrl === base || originalUrl.startsWith(`${base}/`)) return '';
  const idx = originalUrl.indexOf(SUPABASE_PUBLIC_MARKER);
  if (idx === -1) return '';
  const key = originalUrl
    .slice(idx + SUPABASE_PUBLIC_MARKER.length)
    .split(/[?#]/)[0];
  if (!key || key.startsWith('/') || key.includes('..') || key.includes('\0')) return '';
  return `${base}/${key}`;
}

/** Ordered image sources: live first, committed mirror second (deduplicated). */
export function mirrorCandidates(originalUrl, prefix = MEDIA_MIRROR_PREFIX) {
  const list = [];
  if (typeof originalUrl === 'string' && originalUrl) list.push(originalUrl);
  const mirror = mirrorUrl(originalUrl, prefix);
  if (mirror && !list.includes(mirror)) list.push(mirror);
  return list;
}

/** Read the catalogue snapshot. Throws when the file is missing/empty. */
export async function fetchCatalogSnapshot(fetchImpl = fetch) {
  if (typeof fetchImpl !== 'function') throw new Error('fetch unavailable');
  const res = await fetchImpl(SNAPSHOT_PATH, {
    cache: 'no-store',
    credentials: 'same-origin',
  });
  if (!res || !res.ok) throw new Error('Catalogue snapshot unavailable');
  const payload = await res.json();
  const rows = Array.isArray(payload && payload.products)
    ? payload.products
    : (Array.isArray(payload) ? payload : null);
  if (!rows || rows.length === 0) throw new Error('Catalogue snapshot is empty');
  return rows;
}

/** A network/timeout/5xx failure means the customer should fall back to WhatsApp. */
export function isOutageError(status) {
  const code = Number(status);
  return code === 0 || code === 408 || code >= 500;
}

export function whatsappUrl(message) {
  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(String(message || ''))}`;
}

/**
 * A compact, bilingual order summary for WhatsApp. Deliberately excludes any
 * price that the server has not confirmed: the support agent completes it.
 */
export function cartWhatsAppMessage(cart, total) {
  const items = Array.isArray(cart) ? cart : [];
  const lines = [
    'مرحبًا ZASHM، عايز أكمّل طلبي عبر واتساب:',
    'Hello ZASHM, I would like to complete my order on WhatsApp:',
    '',
  ];

  items.forEach((item, index) => {
    const product = (item && item.product) || {};
    const parts = [String(product.name || `Item ${index + 1}`)];
    if (item && item.size) parts.push(`مقاس/Size ${item.size}`);
    if (item && item.color) parts.push(String(item.color));
    parts.push(`×${Number(item && item.qty) || 1}`);
    lines.push(`• ${parts.join(' — ')}`);
  });

  const amount = Number(total);
  if (Number.isFinite(amount) && amount > 0) {
    lines.push('', `الإجمالي التقديري / Estimated total: EGP ${amount.toLocaleString('en-EG')}`);
  }

  lines.push('', 'من فضلك أكّدوا التوفر والشحن. / Please confirm availability and delivery.');
  return lines.join('\n');
}
